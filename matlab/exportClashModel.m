function exportClashModel(model, pre, post, fs, outFile, info, removeGravity)
% EXPORTCLASHMODEL  Write ClashModel.h for the Pico 2 firmware.
if nargin < 7, removeGravity = false; end
if nargin < 6, info = ""; end
[C, F] = size(model.W);
fid = fopen(outFile, 'w');
cleaner = onCleanup(@() fclose(fid));

fprintf(fid, '// ============================================================\n');
fprintf(fid, '// ClashModel.h  -  GENERATED by exportClashModel.m, do not edit\n');
fprintf(fid, '// %s\n', char(datetime('now', 'Format', 'yyyy-MM-dd HH:mm')));
fprintf(fid, '// %s\n', char(info));
fprintf(fid, '// Multinomial logistic regression, L2 lambda = %g\n', model.lambda);
fprintf(fid, '// Window: %d samples before + %d after the |a| peak at %d Hz\n', pre, post, fs);
fprintf(fid, '// Classes: 0 = BOTTOM, 1 = MIDDLE, 2 = TOP\n');
fprintf(fid, '// ============================================================\n\n');
fprintf(fid, '#pragma once\n\n');
fprintf(fid, '#define CLASH_MODEL_TRAINED       1\n');
fprintf(fid, '#define CLASH_MODEL_FS_HZ         %d\n', fs);
fprintf(fid, '#define CLASH_MODEL_PRE           %d\n', pre);
fprintf(fid, '#define CLASH_MODEL_POST          %d\n', post);
fprintf(fid, '#define CLASH_MODEL_CLASSES       %d\n', C);
fprintf(fid, '#define CLASH_MODEL_NUM_FEATURES  %d\n', F);
fprintf(fid, '#define CLASH_MODEL_GRAVITY_REMOVED %d\n\n', double(removeGravity));

writeArray(fid, 'clashMu', model.mu);
writeArray(fid, 'clashSigma', model.sigma);
writeArray(fid, 'clashB', model.b');

fprintf(fid, 'static const float clashW[%d][%d] = {\n', C, F);
for c = 1:C
    fprintf(fid, '  {');
    fprintf(fid, '%.9ef, ', model.W(c, 1:end-1));
    fprintf(fid, '%.9ef}%s\n', model.W(c, end), ternary(c < C, ',', ''));
end
fprintf(fid, '};\n');
fprintf('Model exported to %s\n', outFile);
end

function writeArray(fid, name, v)
fprintf(fid, 'static const float %s[%d] = {', name, numel(v));
fprintf(fid, '%.9ef, ', v(1:end-1));
fprintf(fid, '%.9ef};\n\n', v(end));
end

function out = ternary(c, a, b)
if c, out = a; else, out = b; end
end
